/**
 * Check if a GPS coordinate is inside Barangay Pag-Asa
 * @param {number} lat
 * @param {number} lng
 * @returns {boolean}
 */
export function isInsidePagAsa(lat, lng) {
  const point = [lng, lat]; // GeoJSON uses [lng, lat] order
  const polygon = pagAsaBoundary.geometry.coordinates[0];
  return pointInPolygon(point, polygon);
}

/**
 * Ray-casting algorithm — no library needed
 * @param {number[]} point
 * @param {number[][]} polygon
 * @returns {boolean}
 */
function pointInPolygon(point, polygon) {
  const [x, y] = point;
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const [xi, yi] = polygon[i];
    const [xj, yj] = polygon[j];
    const intersect = ((yi > y) !== (yj > y)) &&
      (x < (xj - xi) * (y - yi) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}